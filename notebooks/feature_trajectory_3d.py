from itertools import product, combinations
from mpl_toolkits.mplot3d.art3d import Line3D
def draw_3d_box(ax, color='0.3', lw=1.2):
    xlim = ax.get_xlim()
    ylim = ax.get_ylim()
    zlim = ax.get_zlim()

    corners = list(product(xlim, ylim, zlim))

    for p1, p2 in combinations(corners, 2):
        if sum(p1[i] != p2[i] for i in range(3)) == 1:

            # Draw background lines lighter.
            line_entries = [p1[0], p1[1], p1[2], p2[0], p2[1], p2[2]]
            if line_entries in[
                [xlim[0], ylim[0], zlim[0], xlim[0], ylim[1], zlim[0]],
                [xlim[0], ylim[1], zlim[0], xlim[1], ylim[1], zlim[0]],
                [xlim[0], ylim[1], zlim[0], xlim[0], ylim[1], zlim[1]]
            ]:
                ax.add_line(Line3D(
                    [p1[0], p2[0]],
                    [p1[1], p2[1]],
                    [p1[2], p2[2]],
                    color='#787878',
                    linewidth=lw,
                ))

            # Don't do closest lines.
            elif line_entries not in [
                [xlim[0], ylim[0], zlim[1], xlim[1], ylim[0], zlim[1]],
                [xlim[1], ylim[0], zlim[1], xlim[1], ylim[1], zlim[1]],
                [xlim[1], ylim[0], zlim[0], xlim[1], ylim[0], zlim[1]]
            ]:
                ax.add_line(Line3D(
                    [p1[0], p2[0]],
                    [p1[1], p2[1]],
                    [p1[2], p2[2]],
                    color=color,
                    linewidth=lw
                ))

draw_3d_box(ax)

